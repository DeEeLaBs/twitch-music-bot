import {test} from 'node:test';
import assert from 'node:assert/strict';
import express from 'express';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {createApiRouter} from '../src/server/apiRouter.ts';
import {WheelService} from '../src/server/wheelService.ts';
import {botService} from '../src/server/botService.ts';
import {errorPayload} from '../src/server/errors.ts';
test('wheel API preserves session protection and synchronizes authorized sources',async t=>{
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'wheel-api-'));t.after(()=>fs.rmSync(dir,{recursive:true,force:true}));
 const wheel=new WheelService(path.join(dir,'wheel.json'));
 const token=botService.overlayTokenMatches;const library=Object.getOwnPropertyDescriptor(botService,'overlayLibrary');
 botService.overlayTokenMatches=value=>value==='test-token';Object.defineProperty(botService,'overlayLibrary',{configurable:true,value:{get:(id:string)=>{if(id!=='one'&&id!=='two')throw Error();return {options:{scene:{widgets:[{type:'wheel',visible:true}]}}};}}});
 t.after(()=>{botService.overlayTokenMatches=token;if(library)Object.defineProperty(botService,'overlayLibrary',library);else delete (botService as any).overlayLibrary;});
 const app=express();app.use(express.json());app.use('/api',createApiRouter({sessionToken:'test-session',appVersion:'test',overlayAssetsDir:dir,wheel}));app.use((error:any,_req:any,res:any,_next:any)=>{const p=errorPayload(error);res.status(p.status).json(p.body);});
 const server=app.listen(0,'127.0.0.1');await new Promise<void>(resolve=>server.once('listening',resolve));t.after(()=>server.close());const address=server.address() as {port:number};const base=`http://127.0.0.1:${address.port}/api/wheel`;
 const post=(action:string,body={},session='test-session')=>fetch(`${base}/${action}`,{method:'POST',headers:{'Content-Type':'application/json','X-Bot-Session':session},body:JSON.stringify(body)});
 assert.equal((await fetch(base)).status,200);assert.equal((await post('show',{},'wrong')).status,403);
 assert.equal((await fetch(base+'/output?token=wrong&overlayId=one')).status,404);
 assert.equal((await fetch(base+'/output?token=test-token&overlayId=missing')).status,404);
 assert.equal((await post('configure',{fields:[]})).status,400);
 const ready=await (await post('show')).json();const results=await Promise.all(Array.from({length:4},()=>post('spin',{operationId:ready.operationId}).then(r=>r.json())));
 assert.ok(results.every(r=>r.operationId===ready.operationId&&r.winner===results[0].winner));
 const [a,b]=await Promise.all(['one','two'].map(id=>fetch(base+`/output?token=test-token&overlayId=${id}`).then(r=>r.json())));
 assert.equal(a.startedAt,b.startedAt);assert.equal(a.winner,b.winner);assert.equal(a.operationId,b.operationId);
 assert.equal((await post('hide')).status,400);assert.equal((await post('spin',{operationId:'stale'})).status,400);
});
